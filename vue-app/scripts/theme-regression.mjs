import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = (p) => readFileSync(p,'utf8')
const app=read('src/App.vue'), entry=read('src/main.ts')
const glass=read('src/assets/glass-104-exact.css')
const note=read('src/assets/notedesk-201.css')
const modern=read('src/assets/modern-appdown.css')
const panel=read('src/assets/theme-panel.css')
const old=read('references/v1.0.4-reference.html')
const appdown=read('references/appdown-admin-vue3-preview.html')
assert.match(app,/type Page=[^\n]+\|'theme'/,'theme route must be distinct')
assert.match(app,/page==='theme'/,'theme nav missing')
assert.match(app,/class="theme-detail-sidebar"/,'dedicated theme sidebar missing')
assert.match(app,/class="nd-quick-grid"/,'Note Desk shortcuts missing')
assert.match(app,/appearance\.style==='minimal' && editorOpen/,'Note Desk tabs must appear only on edit')
assert.match(app,/class="modern-topbar"/,'AppDown topbar missing')
for (const file of ['glass-104-exact','notedesk-201','modern-appdown','theme-panel'])assert.ok(entry.includes(`./assets/${file}.css`),file+' not loaded')
assert.ok(old.includes('--glass:rgba(255,255,255,.76)'), 'v1.0.4 reference changed')
assert.ok(glass.includes('--fm-glass-panel:rgba(255,255,255,.76)'), 'v1.0.4 glass token mismatch')
assert.ok(old.includes('flex-basis:70px')||old.includes('flex:0 0 70px'), 'v1.0.4 original sidebar geometry not found')
assert.match(glass,/width:70px/,'v1.0.4 sidebar geometry missing')
assert.ok(note.includes('width:254px')&&note.includes('nd-quick-grid')&&note.includes('memo-board'),'Note Desk layout missing')
assert.ok(appdown.includes('--sidebar:244px')&&appdown.includes('--bg:#f7f8fa'),'AppDown reference changed')
assert.ok(modern.includes('width:244px')&&modern.includes('--background:#f7f8fa'),'AppDown sidebar/color missing')
assert.ok(panel.includes('theme-workspace')&&panel.includes('theme-detail-sidebar'),'theme page layout missing')
assert.ok(!app.includes('structuredClone('),'reactive Proxy structuredClone regression')
console.log('PASS: v2.0.1 theme structure, three visual references, independent theme sidebar')
